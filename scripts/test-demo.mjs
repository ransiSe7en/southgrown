import assert from 'node:assert/strict';
import {readFile,mkdir,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
import ts from 'typescript';
const out=resolve('outputs/demo-tests');await mkdir(out,{recursive:true});
for(const name of ['data','demo']){const source=await readFile(`app/${name}.ts`,'utf8');const result=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}});await writeFile(`${out}/${name}.mjs`,result.outputText.replace(/(['"])\.\/data\1/g,"'./data.mjs'"));}
const {createDemoState,demoRequest}=await import(pathToFileURL(`${out}/demo.mjs`).href);
let checks=0;let state=createDemoState();
const request=(path,body)=>{const result=demoRequest(state,path,body);state=result.state;checks++;return result.data;};
const original=JSON.stringify(state);
assert.equal(request('threads').threads.length,3);assert.ok(request('threads').threads.every(t=>t.messages.length>=4));
assert.equal(JSON.stringify(state),original,'Reading data must not mutate the demo seed');
request('message',{thread:'demo-pickup',body:'I will bring an egg carton.'});
assert.equal(request('threads').threads[0].messages.at(-1).sender,'demo-buyer');
state={...state,role:'seller'};assert.equal(request('threads').threads[0].name,'Alex Taylor');
request('message',{thread:'demo-pickup',body:'Thanks Alex, see you at 10.'});
assert.equal(request('threads').threads[0].messages.at(-1).sender,'demo-seller');
state=JSON.parse(JSON.stringify(state));assert.equal(request('threads').threads[0].messages.at(-1).body,'Thanks Alex, see you at 10.');
assert.ok(request('market').listings.some(l=>l.id==='demo-draft-herbs'&&!l.active));
assert.ok(request('market').listings.some(l=>l.seller==='demo-seller'&&l.quantity===0));
const draft=state.listings.find(l=>l.id==='demo-draft-herbs');request('listings',{...draft,active:true});
state={...state,role:'buyer'};assert.ok(request('market').listings.some(l=>l.id===draft.id&&l.active));
assert.throws(()=>request('listings',{...draft,active:true}),/only edit/);checks++;
const foreign=state.listings.find(l=>l.seller!=='demo-seller');const conversation=request('threads',{listing:foreign.id});request('message',{thread:conversation.id,body:'Is this available?'});
state={...state,role:'seller'};assert.ok(!request('threads').threads.some(t=>t.id===conversation.id));
assert.throws(()=>request('message',{thread:conversation.id,body:'Unauthorised reply'}),/not found/);checks++;
request('favorite',{listing:draft.id,saved:true});assert.ok(request('me').favorites.includes(draft.id));
state={...state,role:'buyer'};assert.ok(!request('me').favorites.includes(draft.id));
request('profile',{...state.profiles['demo-buyer'],name:'Updated demo buyer'});assert.equal(request('me').profile.name,'Updated demo buyer');
assert.throws(()=>request('upload',{}),/not available/);checks++;
state=createDemoState();assert.equal(request('threads').threads[0].messages.length,6);assert.ok(!request('market').listings.some(l=>l.id===draft.id));
assert.equal(state.profiles['demo-buyer'].name,'Alex Taylor');assert.equal(state.threads.length,3);
console.log(`${checks} demo checks passed: prepared chats, role switching, replies, persisted state, listing ownership, drafts, sold-out stock, publishing, favourites and reset.`);
